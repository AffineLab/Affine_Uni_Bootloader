#!/usr/bin/env python3
"""Turns a stamped, guarded STM32G431 bootloader image into the C source the
bootloader updater (targets/stm32g431_blupdater) carries.

    python tools/embed_bl_image.py bootloader_stm32g431.bin OUT_DIR [--record-offset 0x1D8]

Writes OUT_DIR/v3_bl_image.c and OUT_DIR/v3_bl_image.h. Refuses an image whose
guard record is missing or was never stamped (tools/patch_boot_guard.py), or
whose sum does not match: the updater relies on the guard to make a power loss
after the first page recoverable.
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

MAGIC = 0x44524147
PAGE = 0x800


def body_sum(body: bytes) -> int:
    total = 0
    for (word,) in struct.iter_unpack("<I", body):
        total = (((total << 5) | (total >> 27)) & 0xFFFFFFFF) ^ word
    return total


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bin")
    ap.add_argument("out_dir")
    ap.add_argument("--record-offset", type=lambda v: int(v, 0), default=0x1D8)
    opts = ap.parse_args()

    image = bytearray(open(opts.bin, "rb").read())
    magic, length, expected = struct.unpack_from("<III", image, opts.record_offset)
    if magic != MAGIC:
        raise SystemExit(f"no guard record at offset {opts.record_offset:#x}: not a guarded build")
    if length == 0:
        raise SystemExit("guard record not stamped: run tools/patch_boot_guard.py first")
    start = len(image) - length
    if not opts.record_offset + 16 <= start <= PAGE or body_sum(bytes(image[start:])) != expected:
        raise SystemExit("guard record does not match the image")
    stamped_size = len(image)
    # Flash takes whole double-words; the padding lies past what the guard checks.
    while len(image) % 8:
        image.append(0xFF)

    os.makedirs(opts.out_dir, exist_ok=True)
    with open(os.path.join(opts.out_dir, "v3_bl_image.h"), "w", newline="\n") as f:
        f.write(
            "/* Generated by tools/embed_bl_image.py. Do not edit. */\n"
            "#ifndef V3_BL_IMAGE_H\n#define V3_BL_IMAGE_H\n\n#include <stdint.h>\n\n"
            f"#define V3_BL_IMAGE_SIZE {len(image)}u\n"
            f"#define V3_BL_STAMPED_SIZE {stamped_size}u /* before padding: the guard body ends here */\n"
            f"#define V3_BL_GUARD_RECORD_OFFSET 0x{opts.record_offset:X}u\n\n"
            "extern const uint8_t g_v3_bl_image[V3_BL_IMAGE_SIZE];\n\n#endif\n"
        )
    with open(os.path.join(opts.out_dir, "v3_bl_image.c"), "w", newline="\n") as f:
        f.write("/* Generated by tools/embed_bl_image.py. Do not edit. */\n")
        f.write('#include "v3_bl_image.h"\n\n')
        f.write("const uint8_t g_v3_bl_image[V3_BL_IMAGE_SIZE] __attribute__((aligned(8))) = {\n")
        for offset in range(0, len(image), 12):
            f.write("    " + ", ".join(f"0x{b:02X}" for b in image[offset: offset + 12]) + ",\n")
        f.write("};\n")
    print(f"embedded {len(image)} bytes, guard body {length} bytes, sum {expected:08X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
